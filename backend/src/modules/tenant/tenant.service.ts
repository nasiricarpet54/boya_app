import { ConflictException, Injectable, NotFoundException } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { QueryFailedError, Repository } from 'typeorm';

import { Tenant } from './entities/tenant.entity';

/** Postgres `unique_violation`. */
const PG_UNIQUE_VIOLATION = '23505';

export interface CreateTenantInput {
  name: string;
  slug: string;
}

@Injectable()
export class TenantService {
  constructor(@InjectRepository(Tenant) private readonly tenants: Repository<Tenant>) {}

  async findById(id: string): Promise<Tenant> {
    const tenant = await this.tenants.findOne({ where: { id } });
    if (!tenant) throw new NotFoundException('سالن مورد نظر یافت نشد');
    return tenant;
  }

  /**
   * Creates a salon in the pre-review state (ADR-010 onboarding), ready for an
   * admin to invite its owner.
   *
   * `status: 'draft'` is deliberate and is the schema default: an admin creating
   * the tenant is bookkeeping, not approval. The salon goes live only once an
   * admin approves it (`PATCH /admin/tenants/:id/status`), which is what keeps
   * "an admin typed a name" from being equivalent to "this salon is published".
   *
   * `tenants` carries no RLS — it is the registry the RLS policies key off — so
   * this is a plain insert on the pool connection; no tenant GUC is needed (and
   * none exists yet: the tenant's id is generated by this very statement).
   */
  async create(input: CreateTenantInput): Promise<Tenant> {
    const tenant = this.tenants.create({
      name: input.name,
      slug: input.slug,
      status: 'draft',
      isActive: true,
    });

    try {
      return await this.tenants.save(tenant);
    } catch (error) {
      // The only unique constraint a create can trip is `tenants.slug`, so a
      // duplicate is a 409 with a message the panel can show verbatim, rather
      // than a driver error surfacing as a 500.
      if (error instanceof QueryFailedError && (error as { code?: string }).code === PG_UNIQUE_VIOLATION) {
        throw new ConflictException('این شناسه سالن قبلاً استفاده شده است');
      }
      throw error;
    }
  }
}

